# -*- coding: utf-8 -*-
"""Generate PyInstaller VSVersionInfo text file from tray_common metadata."""

from __future__ import annotations

import os
import sys

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT_DIR not in sys.path:
    sys.path.insert(0, ROOT_DIR)

import tray_common  # noqa: E402


def _version_quad(ver_str: str) -> tuple[int, int, int, int]:
    parts: list[int] = []
    for seg in str(ver_str or "0").lstrip("vV").split("."):
        digits = "".join(ch for ch in seg if ch.isdigit())
        parts.append(int(digits) if digits else 0)
    while len(parts) < 4:
        parts.append(0)
    return (parts[0], parts[1], parts[2], parts[3])


def render_version_info() -> str:
    ver = str(getattr(tray_common, "APP_VERSION", "1.1.2"))
    app_name = str(getattr(tray_common, "APP_NAME", "外设电量查看器"))
    build_date = str(getattr(tray_common, "APP_BUILD_DATE", ""))
    quad = _version_quad(ver)
    file_ver_str = ".".join(str(x) for x in quad)
    return f"""# UTF-8
#
# Auto-generated by tools/make_version_info.py
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={quad},
    prodvers={quad},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '080404B0',
          [
            StringStruct('CompanyName', 'Peripheral Battery Viewer'),
            StringStruct('FileDescription', '{app_name} - 2.4G / 蓝牙 / BLE 外设电量监测'),
            StringStruct('FileVersion', '{file_ver_str}'),
            StringStruct('InternalName', '{app_name}'),
            StringStruct('LegalCopyright', 'Build {build_date}'),
            StringStruct('OriginalFilename', '{app_name}.exe'),
            StringStruct('ProductName', '{app_name}'),
            StringStruct('ProductVersion', '{ver}'),
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [2052, 1200])])
  ]
)
"""


def main() -> int:
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT_DIR, ".build_tmp", "file_version_info.txt")
    parent = os.path.dirname(os.path.abspath(out_path))
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(render_version_info())
    print(f"Generated version info ({tray_common.APP_VERSION}) -> {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
